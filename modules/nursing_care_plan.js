function listPlans(ctx) {
  let items = h(ctx, 'nursing_care_plans');
  if (ctx.query.patientId) items = items.filter(x => x.patientId === ctx.query.patientId);
  if (ctx.query.status) items = items.filter(x => x.status === ctx.query.status);
  items.sort((a, b) => sd(b.createdAt) - sd(a.createdAt));
  return { items, total: items.length };
}

function getPlan(ctx) {
  const p = ctx.store.get('nursing_care_plans', ctx.params.id);
  if (!p) throw ctx.E.notFound('care_plan_not_found');
  return p;
}

function createPlan(ctx) {
  const b = ctx.body || {};
  if (!b.patientId) throw ctx.E.badRequest('patient_id_required');
  if (!Array.isArray(b.diagnoses) || !b.diagnoses.length) throw ctx.E.badRequest('at_least_one_diagnosis');
  const patient = ctx.store.get('patients', b.patientId);
  if (!patient) throw ctx.E.notFound('patient_not_found');

  const diagnoses = [];
  for (const d of b.diagnoses) {
    const n = NANDA[d.code];
    if (!n) throw ctx.E.badRequest('unknown_nanda:' + d.code);
    diagnoses.push({
      code: d.code, fa: n.fa, en: n.en, domain: n.domain, is_risk: !!n.risk,
      expectedOutcomes: (d.noc || n.noc || []).map(c => NOC[c]).filter(Boolean).map(o => ({
        code: o.code, fa: o.fa, target: o.target || 4,
        latestScore: null, latestScoredAt: null
      })),
      interventions: (d.nic || n.nic || []).map(c => NIC[c]).filter(Boolean).map(i => ({
        code: i.code, fa: i.fa, activities: i.activities,
        selectedActivities: d.activities ? (d.activities[i.code] || []) : i.activities,
        implemented: false, implementedAt: null, implementedBy: null
      })),
      status: 'active',
      resolvedAt: null, resolvedBy: null,
      notes: d.notes || '',
      addedAt: ctx.now(), addedBy: ctx.actor.id, addedByName: ctx.actor.fullName || ctx.actor.username
    });
  }

  const plan = {
    id: ctx.uid('ncp'),
    patientId: patient.id,
    patientName: patient.firstName + ' ' + patient.lastName,
    wardCode: patient.wardCode,
    bedNumber: patient.bedNumber,
    status: 'draft',
    diagnoses,
    shiftScoring: [],
    handoffLink: null,
    createdBy: ctx.actor.id,
    createdByName: ctx.actor.fullName || ctx.actor.username,
    createdAt: ctx.now()
  };
  ctx.store.put('nursing_care_plans', plan);
  ctx.audit.write('nursing_care_plan', 'plan.create', plan.id, ctx.actor, {
    patientId: patient.id, diagnosisCount: diagnoses.length
  });
  const sg = sig.signAction({
    userId: ctx.actor.id, action: 'create', collection: 'nursing_care_plans',
    recordId: plan.id, data: { patientId: patient.id, diagnoses: diagnoses.map(d => d.code) }
  });
  ctx.store.put('signatures', sg);
  plan.lastSignatureId = sg.id;
  ctx.store.put('nursing_care_plans', plan);
  bus.emit('nursing.care_plan.created', { record: plan, actor: ctx.actor });
  return plan;
}

function activatePlan(ctx) {
  const p = ctx.store.get('nursing_care_plans', ctx.params.id);
  if (!p) throw ctx.E.notFound('care_plan_not_found');
  if (p.status !== 'draft') throw ctx.E.conflict('not_draft');
  p.status = 'active';
  p.activatedAt = ctx.now();
  p.activatedBy = ctx.actor.id;
  p.activatedByName = ctx.actor.fullName || ctx.actor.username;
  ctx.store.put('nursing_care_plans', p);
  ctx.audit.write('nursing_care_plan', 'plan.activate', p.id, ctx.actor, {});
  bus.emit('nursing.care_plan.activated', { record: p, actor: ctx.actor });
  return p;
}

function addDiagnosis(ctx) {
  const p = ctx.store.get('nursing_care_plans', ctx.params.id);
  if (!p) throw ctx.E.notFound('care_plan_not_found');
  if (!['draft','active'].includes(p.status)) throw ctx.E.conflict('plan_closed');
  const b = ctx.body || {};
  const n = NANDA[b.code];
  if (!n) throw ctx.E.badRequest('unknown_nanda:' + b.code);
  if (p.diagnoses.find(d => d.code === b.code)) throw ctx.E.conflict('diagnosis_exists');
  p.diagnoses.push({
    code: b.code, fa: n.fa, en: n.en, domain: n.domain, is_risk: !!n.risk,
    expectedOutcomes: (n.noc || []).map(c => NOC[c]).filter(Boolean).map(o => ({
      code: o.code, fa: o.fa, target: o.target || 4, latestScore: null, latestScoredAt: null
    })),
    interventions: (n.nic || []).map(c => NIC[c]).filter(Boolean).map(i => ({
      code: i.code, fa: i.fa, activities: i.activities,
      selectedActivities: i.activities,
      implemented: false, implementedAt: null, implementedBy: null
    })),
    status: 'active',
    addedAt: ctx.now(), addedBy: ctx.actor.id,
    addedByName: ctx.actor.fullName || ctx.actor.username
  });
  ctx.store.put('nursing_care_plans', p);
  ctx.audit.write('nursing_care_plan', 'plan.add_diagnosis', p.id, ctx.actor, { code: b.code });
  return p;
}

function removeDiagnosis(ctx) {
  const p = ctx.store.get('nursing_care_plans', ctx.params.id);
  if (!p) throw ctx.E.notFound('care_plan_not_found');
  p.diagnoses = p.diagnoses.filter(d => d.code !== ctx.params.code);
  ctx.store.put('nursing_care_plans', p);
  return p;
}

function resolveDiagnosis(ctx) {
  const p = ctx.store.get('nursing_care_plans', ctx.params.id);
  if (!p) throw ctx.E.notFound('care_plan_not_found');
  const d = p.diagnoses.find(x => x.code === ctx.params.code);
  if (!d) throw ctx.E.notFound('diagnosis_in_plan_not_found');
  if (d.status === 'resolved') throw ctx.E.conflict('already_resolved');
  d.status = 'resolved';
  d.resolvedAt = ctx.now();
  d.resolvedBy = ctx.actor.id;
  d.resolvedByName = ctx.actor.fullName || ctx.actor.username;
  d.resolutionNote = (ctx.body && ctx.body.note) || '';
  const active = p.diagnoses.filter(x => x.status === 'active').length;
  if (active === 0) {
    p.status = 'resolved';
    p.resolvedAt = ctx.now();
  }
  ctx.store.put('nursing_care_plans', p);
  ctx.audit.write('nursing_care_plan', 'plan.resolve_diagnosis', p.id, ctx.actor, { code: ctx.params.code });
  bus.emit('nursing.care_plan.diagnosis_resolved', { record: p, code: ctx.params.code, actor: ctx.actor });
  return p;
}

// ═══════════════════════════════════════════════════════════
//  NOC Scoring
// ═══════════════════════════════════════════════════════════
function scoreNOC(ctx) {
  const p = ctx.store.get('nursing_care_plans', ctx.params.id);
  if (!p) throw ctx.E.notFound('care_plan_not_found');
  if (p.status !== 'active') throw ctx.E.conflict('plan_must_be_active');
  const b = ctx.body || {};
  if (!b.diagnosisCode || !b.outcomeCode) throw ctx.E.badRequest('diagnosis_outcome_required');
  if (!Array.isArray(b.scores) || !b.scores.length) throw ctx.E.badRequest('scores_required');
  const d = p.diagnoses.find(x => x.code === b.diagnosisCode);
  if (!d) throw ctx.E.notFound('diagnosis_in_plan_not_found');
  const o = d.expectedOutcomes.find(x => x.code === b.outcomeCode);
  if (!o) throw ctx.E.notFound('outcome_not_found');
  const noc = NOC[b.outcomeCode];
  if (!noc) throw ctx.E.notFound('noc_definition_not_found');

  // Validate: each score 1-5
  for (const s of b.scores) {
    const v = Number(s.score);
    if (!v || v < 1 || v > 5) throw ctx.E.badRequest('invalid_score:' + s.indicator);
  }

  const avg = Math.round(b.scores.reduce((sum, s) => sum + Number(s.score), 0) / b.scores.length * 10) / 10;
  const target = o.target || 4;
  const met = avg >= target;

  const rec = {
    id: ctx.uid('nocs'),
    planId: p.id, patientId: p.patientId, patientName: p.patientName,
    diagnosisCode: b.diagnosisCode, diagnosisFa: d.fa,
    outcomeCode: b.outcomeCode, outcomeFa: o.fa,
    scores: b.scores,
    avg, target, met,
    scoredBy: ctx.actor.id,
    scoredByName: ctx.actor.fullName || ctx.actor.username,
    scoredAt: ctx.now(),
    shift: b.shift || 'current'
  };
  ctx.store.put('noc_scores', rec);

  // Update outcome latest score
  o.latestScore = avg;
  o.latestScoredAt = ctx.now();
  o.history = o.history || [];
  o.history.push({ avg, met, at: ctx.now(), by: ctx.actor.id });
  if (o.history.length > 20) o.history = o.history.slice(-20);

  // NOC crisis: if avg drops < 2, emit alert
  if (avg < 2) {
    bus.emit('cdss.alert', {
      type: 'noc_crisis', severity: 'critical',
      patientId: p.patientId, patientName: p.patientName,
      title: '🚨 NOC بحرانی — ' + p.patientName,
      message: o.fa + ': میانگین ' + avg + '/5 (هدف ' + target + ')',
      recommendation: 'بازبینی فوری مداخلات NIC — تماس با پزشک'
    });
  } else if (!met) {
    bus.emit('cdss.alert', {
      type: 'noc_not_met', severity: 'warning',
      patientId: p.patientId, patientName: p.patientName,
      title: '⚠️ NOC زیر هدف — ' + p.patientName,
      message: o.fa + ': ' + avg + '/5 (هدف ' + target + ')',
      recommendation: 'افزایش مداخلات یا بازنگری برنامه'
    });
  }

  ctx.store.put('nursing_care_plans', p);
  ctx.audit.write('nursing_care_plan', 'noc.score', rec.id, ctx.actor, {
    planId: p.id, outcome: b.outcomeCode, avg
  });
  bus.emit('nursing.care_plan.noc_scored', { record: rec, actor: ctx.actor });
  return rec;
}

function nocHistory(ctx) {
  let items = h(ctx, 'noc_scores');
  if (ctx.query.planId) items = items.filter(x => x.planId === ctx.query.planId);
  if (ctx.query.patientId) items = items.filter(x => x.patientId === ctx.query.patientId);
  items.sort((a, b) => sd(b.scoredAt) - sd(a.scoredAt));
  return { items, total: items.length };
}

// ═══════════════════════════════════════════════════════════
//  Handoff Integration (feeds nursing_report ISBAR)
// ═══════════════════════════════════════════════════════════
function handoffSummary(ctx) {
  const pid = ctx.params.patientId;
  const plan = h(ctx, 'nursing_care_plans').find(x => x.patientId === pid && x.status === 'active');
  if (!plan) return { hasPlan: false, patientId: pid };
  const active = plan.diagnoses.filter(d => d.status === 'active');
  const resolved = plan.diagnoses.filter(d => d.status === 'resolved');
  const outcomes = [];
  for (const d of active) {
    for (const o of d.expectedOutcomes) {
      if (o.latestScore != null) {
        outcomes.push({
          diagnosis: d.fa, outcome: o.fa,
          score: o.latestScore, target: o.target,
          met: o.latestScore >= o.target
        });
      }
    }
  }
  return {
    hasPlan: true,
    planId: plan.id,
    patientId: pid,
    patientName: plan.patientName,
    activeDiagnoses: active.map(d => ({ code: d.code, fa: d.fa, since: d.addedAt })),
    resolvedDiagnoses: resolved.map(d => ({ code: d.code, fa: d.fa, since: d.resolvedAt })),
    outcomes,
    summaryFa: active.length + ' تشخیص فعال، ' + resolved.length + ' حل‌شده',
    text: active.map(d => '• ' + d.fa).join('\n'),
    generatedAt: ctx.now()
  };
}

