function suggestDiagnoses(ctx, patient) {
  if (!patient) return { items: [] };
  const pid = patient.id;
  const vitals = h(ctx, 'vitals').filter(v => v.patientId === pid).sort((a,b) => sd(b.recordedAt) - sd(a.recordedAt));
  const mar = h(ctx, 'mar').filter(m => m.patientId === pid);
  const labs = h(ctx, 'labs').filter(l => l.patientId === pid);
  const isolations = h(ctx, 'isolations').filter(i => i.patientId === pid && i.status === 'active');
  const last = vitals[0] || {};
  const suggestions = [];
  const seen = new Set();

  function add(code, reason, confidence) {
    if (seen.has(code)) return;
    if (!NANDA[code]) return;
    seen.add(code);
    const n = NANDA[code];
    suggestions.push({
      code, fa: n.fa, en: n.en, domain: n.domain,
      is_risk: !!n.risk, reason, confidence,
      nic: n.nic || [], noc: n.noc || []
    });
  }

  // Vitals-based
  if (last.news2 >= 7) {
    add('00126', 'NEWS2 ' + last.news2 + ' — احتمال شوک/نارسایی', 'high');
    add('00032', 'NEWS2 ' + last.news2 + ' — الگوی تنفسی', 'high');
  } else if (last.news2 >= 5) {
    add('00032', 'NEWS2 ' + last.news2, 'medium');
    add('00029', 'NEWS2 ' + last.news2, 'medium');
  }
  if (last.spo2 && last.spo2 < 92) {
    add('00030', 'SpO2 ' + last.spo2 + '%', 'high');
    add('00031', 'اکسیژن‌درمانی', 'medium');
  }
  if (last.gcs && last.gcs < 15) {
    add('00128', 'GCS ' + last.gcs, 'high');
    add('00129', 'GCS کاهش‌یافته', 'medium');
  }
  if (last.temp && last.temp >= 38.3) {
    add('00004', 'تب ' + last.temp + '°C', 'high');
  }
  if (last.bp_sys && last.bp_sys < 90) {
    add('00027', 'SBP ' + last.bp_sys, 'high');
  }
  if (last.hr && last.hr > 110) {
    add('00029', 'HR ' + last.hr, 'medium');
  }

  // Diagnosis-based
  const dx = String(patient.diagnosis || '').toLowerCase();
  if (dx.indexOf('سپسیس') >= 0 || dx.indexOf('sepsis') >= 0) {
    add('00126', 'سپسیس — خطر شوک', 'high');
    add('00004', 'منبع عفونی', 'high');
    add('00026', 'مایع‌درمانی سپسیس', 'medium');
  }
  if (dx.indexOf('سکته') >= 0 || dx.indexOf('cva') >= 0 || dx.indexOf('stroke') >= 0) {
    add('00103', 'اختلال بلع پس از CVA', 'high');
    add('00085', 'اختلال حرکتی', 'high');
    add('00122', 'آفازی احتمالی', 'medium');
    add('00040', 'بی‌تحرکی', 'medium');
  }
  if (dx.indexOf('chf') >= 0 || dx.indexOf('قلب') >= 0) {
    add('00026', 'CHF — افزایش حجم', 'high');
    add('00029', 'کاهش برون‌ده قلبی', 'high');
    add('00092', 'عدم تحمل فعالیت', 'medium');
  }
  if (dx.indexOf('copd') >= 0 || dx.indexOf('پنومونی') >= 0 || dx.indexOf('pneumonia') >= 0) {
    add('00031', 'پاک‌سازی راه هوایی', 'high');
    add('00032', 'الگوی تنفسی', 'high');
    add('00004', 'عفونت تنفسی', 'medium');
  }
  if (dx.indexOf('dm') >= 0 || dx.indexOf('دیابت') >= 0 || dx.indexOf('dka') >= 0) {
    add('00179', 'دیابت — قند ناپایدار', 'high');
    add('00025', 'اختلال الکترولیت', 'medium');
  }
  if (dx.indexOf('akI') >= 0 || dx.indexOf('نارسایی کلیه') >= 0 || dx.indexOf('ckd') >= 0) {
    add('00026', 'نارسایی کلیه', 'high');
    add('00025', 'اختلال الکترولیت', 'high');
    add('00028', 'کنترل مایعات', 'medium');
  }
  if (dx.indexOf('پارکینسون') >= 0 || dx.indexOf('ms') >= 0) {
    add('00085', 'اختلال حرکتی', 'high');
    add('00103', 'اختلال بلع', 'high');
    add('00122', 'اختلال گفتار', 'medium');
  }
  if (dx.indexOf('شکستگی') >= 0 || dx.indexOf('fracture') >= 0) {
    add('00132', 'درد حاد', 'high');
    add('00085', 'اختلال حرکتی', 'high');
    add('00037', 'خطر نوروواسکولار', 'medium');
    add('00047', 'خطر زخم فشاری', 'medium');
    add('00155', 'خطر سقوط', 'high');
  }
  if (dx.indexOf('آپاندیسیت') >= 0 || dx.indexOf('جراحی') >= 0 || dx.indexOf('post') >= 0) {
    add('00132', 'درد حاد پس از جراحی', 'high');
    add('00004', 'خطر عفونت محل جراحی', 'high');
    add('00085', 'اختلال تحرک', 'medium');
    add('00011', 'یبوست پس از جراحی/اپیوئید', 'medium');
  }
  if (dx.indexOf('سرطان') >= 0 || dx.indexOf('cancer') >= 0 || dx.indexOf('chemo') >= 0) {
    add('00134', 'تهوع شیمی‌درمانی', 'high');
    add('00002', 'سوءتغذیه', 'high');
    add('00040', 'بی‌تحرکی', 'medium');
    add('00132', 'درد', 'medium');
  }
  if (dx.indexOf('تروما') >= 0 || dx.indexOf('trauma') >= 0) {
    add('00100', 'خطر خونریزی', 'high');
    add('00046', 'اختلال پوست', 'high');
    add('00132', 'درد', 'high');
    add('00027', 'کمبود حجم', 'high');
  }

  // Isolation
  if (isolations.length) {
    const type = isolations[0].type;
    add('00004', 'ایزولاسیون ' + type, 'high');
  }

  // MAR (PRN pain, insulin)
  const prnPain = mar.some(m => m.status === 'given' && /morphine|fentanyl|opioid|acetaminophen/i.test(m.drugName || ''));
  if (prnPain) add('00132', 'داروی PRN درد مصرف شده', 'high');
  const insulin = mar.some(m => m.status === 'given' && /insulin/i.test(m.drugName || ''));
  if (insulin) add('00179', 'انسولین تجویزشده', 'high');

  // Age-based
  if (patient.age >= 65) {
    add('00155', 'سالمند — خطر سقوط', 'medium');
    add('00201', 'سالمند — خطر زخم فشاری', 'medium');
    add('00095', 'سالمند — اختلال خواب', 'low');
  }
  if (patient.age >= 80) {
    add('00196', 'سالمند ضعیف — نارسایی رشد', 'medium');
  }

  // Immobility (any patient with bed rest)
  if (patient.status === 'in_care' && (patient.wardCode || '').indexOf('ICU') >= 0) {
    add('00040', 'بی‌تحرکی ICU', 'high');
    add('00047', 'خطر زخم فشاری ICU', 'high');
    add('00155', 'خطر سقوط ICU', 'medium');
    add('00069', 'اضطراب محیط ICU', 'medium');
  }

  return { items: suggestions, total: suggestions.length, patientId: pid };
}

