function listNanda(ctx) {
  const items = Object.values(NANDA).map(n => ({
    code: n.code, domain: n.domain, fa: n.fa, en: n.en,
    is_risk: !!n.risk, is_actual: !n.risk,
    nic_count: (n.nic || []).length, noc_count: (n.noc || []).length
  }));
  const byDomain = {};
  items.forEach(i => { if (!byDomain[i.domain]) byDomain[i.domain] = []; byDomain[i.domain].push(i); });
  const domainLabels = {
    1:'ارتقای سلامت', 2:'تغذیه', 3:'دفع و تبادل', 4:'فعالیت و استراحت',
    5:'ادراک و شناخت', 6:'خودادراکی', 7:'نقش‌های ارتباطی', 8:'جنسیت',
    9:'مقابله و تحمل استرس', 10:'اصول زندگی', 11:'امنیت و حفاظت',
    12:'راحتی', 13:'رشد و تکامل'
  };
  return { items, total: items.length, byDomain, domainLabels };
}

function getNanda(ctx) {
  const n = NANDA[ctx.params.code];
  if (!n) throw ctx.E.notFound('diagnosis_not_found');
  return {
    diagnosis: n,
    nic: (n.nic || []).map(c => NIC[c]).filter(Boolean),
    noc: (n.noc || []).map(c => NOC[c]).filter(Boolean)
  };
}

function listNic(ctx) {
  const items = Object.values(NIC).map(n => ({ code: n.code, fa: n.fa, activityCount: n.activities.length }));
  return { items, total: items.length };
}

function listNoc(ctx) {
  const items = Object.values(NOC).map(n => ({ code: n.code, fa: n.fa, indicatorCount: n.indicators.length, target: n.target }));
  return { items, total: items.length };
}

function suggest(ctx) {
  const pid = ctx.params.patientId;
  const p = ctx.store.get('patients', pid);
  if (!p) throw ctx.E.notFound('patient_not_found');
  return suggestDiagnoses(ctx, p);
}

